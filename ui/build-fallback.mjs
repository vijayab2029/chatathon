// Regenerates ui/fallback-data.js from the JSON contracts so the demo still
// works when opened straight off the filesystem (file:// blocks fetch).
// Run after your teammates drop in real data:  node ui/build-fallback.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = p => JSON.parse(readFileSync(resolve(here, '..', 'data', p), 'utf8'));

const out = `/* AUTO-GENERATED by ui/build-fallback.mjs — do not edit by hand.
   Mirror of data/*.json, inlined so index.html works over file:// too. */
window.FALLBACK = {
  employee: ${JSON.stringify(read('employee_insight.json'), null, 2)},
  employer: ${JSON.stringify(read('employer_view.json'), null, 2)}
};
`;
writeFileSync(resolve(here, 'fallback-data.js'), out);
console.log('wrote ui/fallback-data.js');
